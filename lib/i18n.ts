import AsyncStorage from "@react-native-async-storage/async-storage";

export type AppLanguage = "en" | "ar" | "ur";
const LANGUAGE_KEY = "hiaccept.language.v1";

export const languageNames: Record<AppLanguage, string> = {
  en: "English",
  ar: "العربية",
  ur: "اردو",
};

export async function loadLanguage(): Promise<AppLanguage | null> {
  const value = await AsyncStorage.getItem(LANGUAGE_KEY);
  return value === "en" || value === "ar" || value === "ur" ? value : null;
}

export async function saveLanguage(language: AppLanguage) {
  await AsyncStorage.setItem(LANGUAGE_KEY, language);
}

